"""Supabase access: sessions persistence.

The backend uses the service role key (tables are closed to anon by RLS).
Session ids are generated by the app so that every save is a plain upsert.
"""

import os
from datetime import date, datetime
from functools import lru_cache

from supabase import Client, create_client

from app.flow import Session


@lru_cache(maxsize=1)
def _client() -> Client:
    return create_client(os.environ["SUPABASE_URL"], os.environ["SUPABASE_SERVICE_ROLE_KEY"])


def session_row(
    session_id: str,
    chw_phone: str,
    session: Session,
    completed_at: datetime | None = None,
    followup_due: date | None = None,
) -> dict:
    """Map a flow Session to a `sessions` row. Contains no name, only the woman's code."""
    row = {
        "id": session_id,
        "chw_phone": chw_phone,
        "woman_code": session.woman_code,
        "consent": session.consent,
        "answers": list(session.answers),
        "safety_flag": session.safety_flag,
    }
    if session.result is not None:
        row["score"] = session.result.score
        row["level"] = session.result.level.value
    if completed_at is not None:
        row["completed_at"] = completed_at.isoformat()
    if followup_due is not None:
        row["followup_due"] = followup_due.isoformat()
    return row


def save_session(row: dict) -> None:
    _client().table("sessions").upsert(row).execute()
